 await view(first).locator('#start').click();await view(first).waitForFunction(()=>document.documentElement.dataset.playing==='true');
 assert.equal((await state()).status,'running');
 await first.keyboard.press('Escape');await leaveBrowserRoom(first,view(first));
 await view(first).locator('#private').click();await view(first).locator('#start').waitFor({state:'visible'});
 second=await page();await view(second).getByRole('button',{name:'TAKE CONTROL',exact:true}).waitFor();
